def main() -> int:
    sc = Scorer()
    실패 = 0

    print("=" * 74)
    print(f" 점수표 검증   수집 {sc.cut_collect}점 이상 / 검토 {sc.cut_review}점 이상")
    print("=" * 74)

    print("\n[1] 검증용_공고목록.md 8건 — 수집 구간에 들어야 함")
    for org, title in 필수:
        div, pts, why = sc.verdict(title, org)
        ok = div == "수집"
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {pts:4d}점 {div}  {title[:52]}")
        if not ok:
            print(f"            근거: {why}")

    print("\n[2] 4개월 데이터에서 확인한 동종 공고 — 수집 구간에 들어야 함")
    for org, title in 추가필수:
        div, pts, why = sc.verdict(title, org)
        ok = div == "수집"
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {pts:4d}점 {div}  {title[:52]}")
        if not ok:
            print(f"            근거: {why}")

    print("\n[3] 일반화 — 아직 안 나왔지만 나오면 잡아야 하는 공고명")
    for org, title in 미래_잡아야:
        div, pts, why = sc.verdict(title, org)
        ok = div == "수집"
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {pts:4d}점 {div}  {title[:52]}")
        if not ok:
            print(f"            근거: {why}")

    print("\n[4] 걸러야 하는 공고명 — 제외 구간이어야 함")
    for org, title in 걸러야:
        div, pts, why = sc.verdict(title, org)
        ok = div == "제외"
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {pts:4d}점 {div}  {title[:52]}")
        if not ok:
            print(f"            근거: {why}")

    print("\n[5] 공고문 자격요건 구간 — 4차 판정")
    from 수집기 import qualification_section  # noqa: PLC0415  여기서만 쓴다

    for label, text in 공고문_잡아야:
        found = sc.pdf_hit(qualification_section(text))
        ok = bool(found)
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {label:24s} → {', '.join(found[:3]) or '적중 없음'}")
    for label, text in 공고문_걸러야:
        found = sc.pdf_hit(qualification_section(text))
        ok = not found
        실패 += not ok
        print(f"  {'OK  ' if ok else '실패'} {label:24s} → {', '.join(found[:3]) or '없음'}")

    # ----------------------------------------------------------------------
    # 진단 엑셀이 있으면 4개월 실적으로 정밀도까지 본다
    # ----------------------------------------------------------------------
    진단 = sorted((HERE / "수집결과").glob("진단_*.xlsx")) if (HERE / "수집결과").exists() else []
    if 진단:
        try:
            import openpyxl
        except ImportError:
            openpyxl = None
        if openpyxl:
            wb = openpyxl.load_workbook(진단[-1], read_only=True)
            rows = []
            for sh in wb.sheetnames:
                if not sh[0].isdigit() or sh.startswith("5"):
                    continue
                for r in wb[sh].iter_rows(min_row=2, values_only=True):
                    rows.append(((r[1] or "") + " " + (r[2] or ""), r[3] or ""))
            if rows:
                수집, 검토 = set(), set()
                for org, title in rows:
                    div, pts, _ = sc.verdict(title, org)
                    if div == "수집":
                        수집.add(title)
                    elif div == "검토":
                        검토.add(title)
                print(f"\n[6] {진단[-1].name} 실적 ({len(rows):,}건)")
                print(f"     자동수집 {len(수집)}건 · 검토후보 {len(검토)}건")
                print(f"     PDF 다운로드 대상 {len(수집) + len(검토)}건")

    print("\n" + "=" * 74)
    if 실패:
        print(f" 실패 {실패}건 — 점수표.yaml 을 다시 확인하세요")
    else:
        print(" 전부 통과")
    print("=" * 74)
    return 1 if 실패 else 0


if __name__ == "__main__":
    raise SystemExit(main())
